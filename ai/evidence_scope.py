from __future__ import annotations

import os


def build_evidence_scope_contract() -> str:
    """Constrain model-owned fact binding and arithmetic using existing chunk scope.

    This is a generation contract, not a local semantic proof checker. No source
    category, business vocabulary or proximity heuristic decides a relationship.
    """
    if os.getenv("DOCMIND_EVIDENCE_SCOPE_BINDING", "1") == "0":
        return ""
    return (
        "【事实关系与派生证据守门】\n"
        "以下约束适用于普通回答、比较、表格、结论、理由、行动和格式回退；"
        "优先于完成计算、填满表格或必须选出对象的要求。\n"
        "1. 属性值出现不等于属性关系成立。每次绑定都须核对：主体身份、具体变体、"
        "限定条件、单位及适用范围，以及证明它们相互对应的原文。"
        "文件名、来源标题、当前焦点、同文件或同chunk共现均不是关系证据。"
        "不得用用户期望的对象、单位或数量替来源补齐这些信息。\n"
        "2. 保留原有chunk位置及其中的段落、区块、表格行、引用和材料性质边界；"
        "同一个chunk也可能包含互不相关的事实。优先使用明确局部关系。"
        "允许跨句、跨chunk和跨来源绑定，但必须有明确的共同主体及限定范围、"
        "指代或交叉引用等关系依据；不得仅凭接近、相同数值或同源拼接。"
        "边界缺失时保持未知，不猜测原始结构。\n"
        "3. 历史陈述、评价、转述和旧版本可用于回答其自身范围的问题，不能自动"
        "升级为当前对象、当前变体或当前有效状态。保留时间、版本、地点和陈述者等"
        "限定；资料获取时间不等于事实生效时间。不得一律丢弃某类材料。\n"
        "4. 任何派生计算前逐项核对：数值有原文依据；对应主体明确；单位和范围明确；"
        "输入量的语义及分子分母兼容；数量、周期或其他换算关系有明确证据；"
        "不是仅由同文件共现拼成；参与证据无未解决的关键冲突。"
        "全部必要条件成立才是 DERIVATION_STATUS=VERIFIED，且仅在任务需要时计算。"
        "缺关系依据为 DERIVATION_STATUS=UNVERIFIED，缺输入为 DERIVATION_STATUS=INSUFFICIENT；"
        "两者均不得输出确定性派生值，也不得先计算再以“待确认”修饰来掩盖未证实的关系。"
        "未知的分母或计量基础不能默认为一，不能以零或N/A代替后继续排名。\n"
        "5. 未经证实的关系及派生值不能成为最低、最优、最匹配或行动优先级的依据。"
        "可比依据不足时暂缓选择，保留各自原始事实、未知关系和需要确认的信息；"
        "仍可按其他已确认条件比较。仅当明确写出缺失前提时允许条件性推演，"
        "前提必须与推演结果同处呈现，不能在其他字段中升级为已确认事实或推荐优势。\n"
        "6. 每个确认事实、未确认关系和条件性推演均保留精确来源。派生结果同时给出"
        "输入事实及其来源，并用简短原文或局部位置说明关系依据；单列来源文件不构成关系证明。"
        "无法绑定时分别陈述来源中出现的事实，明确“对应关系未确认，现有证据不足以计算”。\n"
        "7. 输出前交叉核对所有字段：表格对象名称也不能偷偷加入未经证实的属性；"
        "正文、表格、差异、结论、理由和下一步使用同一事实状态。"
        "若任一必要关系未确认，删除依赖它的确定性计算及排名，改为原始事实与待确认项。"
        "只呈现依据和结果状态，不展示内部推理过程。\n\n"
    )
